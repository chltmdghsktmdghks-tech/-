// ── 4단계 2/N — 베이스/코드/멜로디 패턴 (theory.dart 의 스케일·조·코드 시스템 필요) ──
//
// 웹 `MIDI_LIB.bass/chord/melody` + `LONG_LIB`/`LONG_LIB2` 의 같은 항목을 옮겼다
// (드럼과 같은 순서 — MIDI_LIB → LONG_LIB → LONG_LIB2). 역시 손으로 옮기지 않고 파이썬으로
// 파싱했다 — 이번엔 `arp4()`/`block4()` 헬퍼 호출도 있어서(웹이 64개 아르페지오 음을
// 손으로 안 적으려고 만든 함수), 그 두 함수를 파이썬으로 그대로 재구현해 호출한 뒤
// **결과 값**을 리터럴로 찍어냈다 — 헬퍼 자체를 Dart 로 옮기지 않은 이유는, 결과가
// 정적 데이터라 굳이 런타임에 재계산할 필요가 없어서다(값은 같다, 계산 시점만 다르다).
//
// notes 원소 형식(웹 `buildRows`/`buildChord` 그대로):
//   베이스/멜로디: [도수, step, len(스텝), vel(1~3), glide?]  — 5번째가 1이면 글라이드
//     (앞 음 높이에서 미끄러져 들어온다, 웹 `n.gl`)
//   코드: [코드번호(0~6, 다이아토닉 도수), step, len, vel, 코드타입?, 층?]
//     — 5번째가 있으면(문자열) 그 도수의 코드를 그 타입으로 바꿔 쓴다(웹 `ty`,
//     예: 재즈 진행의 'min7'/'dom7'). 없으면 다이아토닉 기본(장/단/dim)을 쓴다.
//     — 6번째가 있으면(정수) **몇 옥타브 위에서 치는지**다(theory.dart `voiceLead`).
//     한 씬에 코드 악기가 둘일 때 위층을 맡는 줄이 1 을 쓴다. 없으면 0 —
//     같은 진행을 같은 자리에서 치면 한쪽이 다른 쪽에 완전히 묻힌다.
class NotePatternDef {
  final String name;
  final int bars;
  final int src;

  /// 이 판의 **본줄** — 트랙 종류가 정한다(화음 판이면 코드, 나머지는 낱음).
  final List<List<Object?>> notes;

  /// **덧줄** — 본줄과 반대인 것. 화음 판에 얹은 낱음, 가락 판에 얹은 화음.
  ///
  /// 옛 앱(뮤직 두들)은 클립 하나가 `lanes.chord` 와 `lanes.rows` 를 **둘 다**
  /// 들 수 있었다 — 패드로 화음을 깔면서 그 위에 낱음을 몇 개 얹는 것이 한 판
  /// 안에서 됐다. 여기서는 트랙 종류가 본줄을 정하니, 반대쪽을 이 칸에 담는다.
  ///
  /// **비어 있는 것이 보통이다.** 라이브러리 패턴은 전부 비어 있고, 옛 파일에도
  /// 이 칸이 없다 — 있을 때만 저장하고, 없으면 여태와 한 톨도 다르지 않게 돈다.
  final List<List<Object?>> also;

  /// **이 판의 한 마디가 몇 칸인가** (5단계 47/N · 홀수 박자).
  /// 기본값 16이라 옛 판·옛 파일은 한 톨도 안 달라진다. `DrumPatternDef.spb` 참고.
  final int spb;

  const NotePatternDef(
    this.name,
    this.bars,
    this.src,
    this.notes, {
    this.also = const [],
    this.chromatic = false,
    this.spb = kStepsPerBar,
  });

  /// **반음 줄**인가(프로 모드). 참이면 `notes` 의 첫 칸은 스케일 도수가 아니라
  /// **으뜸음에서 몇 반음**이다(0~24).
  ///
  /// 도수 줄은 조에 맞는 음만 낼 수 있다 — 블루 노트도, 지나가는 반음도 못 찍는다.
  /// 라이브러리 판은 전부 도수 줄이고, 옛 파일에도 이 칸이 없다.
  final bool chromatic;

  /// 이 판에서 **한 군데만 바꾼 새 판**.
  ///
  /// 네 칸짜리 생성자로 새로 짜면 `also`·`chromatic` 을 **매번 손으로 옮겨야 한다** —
  /// 한 번만 빠뜨려도 얹어 둔 낱음이 사라지거나(덧줄) 가락이 딴 가락이 된다(반음 줄).
  /// **오류는 안 난다.** 실제로 「막 써 보기」가 그 실수를 잡았다.
  /// 그래서 「바꿀 것만 적는」 길을 둔다 — 안 적은 것은 저절로 따라온다.
  NotePatternDef copyWith({
    String? name,
    int? bars,
    int? src,
    List<List<Object?>>? notes,
    List<List<Object?>>? also,
    bool? chromatic,
    int? spb,
  }) => NotePatternDef(
    name ?? this.name,
    bars ?? this.bars,
    src ?? this.src,
    notes ?? this.notes,
    also: also ?? this.also,
    chromatic: chromatic ?? this.chromatic,
    spb: spb ?? this.spb,
  );

  /// 덧줄만 든 판 — **반대쪽 만드는 이**에게 그대로 넘긴다
  /// (`buildChordPattern`/`buildRowsPattern` 은 `notes` 만 본다).
  /// 덧줄은 늘 화음 아니면 도수 줄이다 — 반음은 본줄에서만 쓴다.
  NotePatternDef get alsoDef =>
      NotePatternDef(name, bars, src, also, spb: spb);
}

/// 웹 `tileNotes()` — 드럼과 같은 로직(patterns.dart 위쪽 `buildDrumPattern` 참고)을
/// 도수 있는 노트 목록에도 그대로 적용한다. 노트의 1번 인덱스(step)만 밀어주면 된다.
///
/// **공개 함수다** — `buildRowsPattern`/`buildChordPattern`(재생)뿐 아니라
/// `Project.makeEditable`(project.dart)도 이 펼치기를 그대로 써야 한다.
/// 예전엔 여기서만 쓰는 비공개 함수였는데, `makeEditable`이 "펼친 걸 쓴다"고
/// 주석만 적어 두고 실제로는 안 펼쳤다(원본 그대로 복사해 놓고 `src=bars`로
/// 표시만 바꿨다) — 반복되는 마디가 편집기를 여는 순간 조용히 사라졌다.
/// 펼치는 코드를 한 곳에 두면 이 문제가 재발할 수 없다.
List<List<Object?>> tileNoteList(
  List<List<Object?>> notes,
  int src,
  int bars, {
  int spb = kStepsPerBar,
}) {
  final reps = src > 0 ? (bars ~/ src).clamp(1, 1 << 20) : 1;
  if (reps <= 1) return notes;
  final out = <List<Object?>>[];
  for (var r = 0; r < reps; r++) {
    final off = r * src * spb;
    for (final n in notes) {
      final copy = List<Object?>.from(n);
      copy[1] = (copy[1] as int) + off;
      out.add(copy);
    }
  }
  return out;
}

/// 베이스/멜로디 타격 하나 — 도수를 이미 실제 주파수로 바꿔 둔 상태(재생 직전 형태).
class MelodicHit {
  final int step;
  final int len; // 스텝 단위 길이
  final int vel;
  final double freq;
  final double glideFromFreq; // 0 이면 글라이드 없음
  const MelodicHit(
    this.step,
    this.len,
    this.vel,
    this.freq,
    this.glideFromFreq,
  );
}

/// 웹 `buildRows()` + 재생 시점의 `prevRowFreq()` 를 합쳐 옮긴 것.
/// 웹은 트랙/클립 구조 안에서 "이 클립 안의 바로 앞 음"을 찾지만, 여기는 아직 클립·타임라인이
/// 없어서(5단계) 패턴 하나(타일링 후 전체)를 그 자체로 하나의 '악절'로 보고 같은 규칙
/// (전체 노트를 스텝 순서로 봤을 때 이 스텝보다 앞선 가장 가까운 노트)을 적용한다.
List<MelodicHit> buildRowsPattern(
  NotePatternDef def,
  String type,
  MusicKey key,
) {
  final tiled = List<List<Object?>>.of(
    tileNoteList(def.notes, def.src, def.bars, spb: def.spb),
  )..sort((a, b) => (a[1] as int).compareTo(b[1] as int));
  // **반음 줄이면 도수가 아니라 반음이다**(프로 모드). 같은 숫자라도 뜻이 다르다.
  final freqs = tiled
      .map(
        (n) => def.chromatic
            ? semiFreq((n[0] as int), type, key)
            : degreeFreq((n[0] as int), type, key),
      )
      .toList(growable: false);
  final out = <MelodicHit>[];
  for (var i = 0; i < tiled.length; i++) {
    final n = tiled[i];
    final step = n[1] as int;
    final glide = n.length > 4 && n[4] == 1;
    var glideFrom = 0.0;
    if (glide) {
      var bestStep = -1;
      for (var j = 0; j < tiled.length; j++) {
        final s = tiled[j][1] as int;
        if (s < step && s > bestStep) {
          bestStep = s;
          glideFrom = freqs[j];
        }
      }
    }
    out.add(MelodicHit(step, n[2] as int, n[3] as int, freqs[i], glideFrom));
  }
  return out;
}

/// 코드 타격 하나 — 코드톤 전 주파수를 이미 계산해 둔 상태.
class ChordHit {
  final int step;
  final int len;
  final int vel;
  final List<double> freqs;
  const ChordHit(this.step, this.len, this.vel, this.freqs);
}

/// 웹 `buildChord()` — 코드번호(다이아토닉 도수)를 [diatonicChords] 로 실제 코드로
/// 바꾸고, 5번째 값(코드타입 문자열)이 있으면 그 도수의 근음은 유지한 채 타입만 바꾼다
/// (웹 `{r:c.spec.r,t:ty,x:[],b:null}` — 텐션·슬래시베이스는 패턴 데이터에 없어 비움).
/// [plainType] 을 주면 **코드 종류를 안 적어 둔 음**만 그 종류로 친다
/// (록 기타의 파워코드 — `genreChordType` 참고). 적어 둔 음은 그대로다:
/// 사용자가 고른 것을 스타일이 덮으면 고를 이유가 없다.
///
/// [voice] 가 `guitar`/`nylon` 이면 [guitarChordMidi] 로 **바레 코드 손 모양**을
/// 그대로 쓴다(자리바꿈 안 함 — 기타는 코드마다 모양을 프렛만 옮겨 짚는다).
List<ChordHit> buildChordPattern(
  NotePatternDef def,
  MusicKey key, {
  String? plainType,
  String? voice,
}) {
  final isGuitar = voice == 'guitar' || voice == 'nylon';
  final tiled = tileNoteList(def.notes, def.src, def.bars, spb: def.spb);
  final chords = diatonicChords(key);
  final specs = <ChordSpec>[];
  final octs = <int>[];
  for (final n in tiled) {
    final idx = ((n[0] as int) % chords.length + chords.length) % chords.length;
    var spec = chords[idx];
    if (plainType != null && !(n.length > 4 && n[4] is String)) {
      spec = ChordSpec(root: spec.root, type: plainType);
    }
    if (n.length > 4 && n[4] is String) {
      // 종류만이 아니라 **텐션·슬래시 베이스**까지 이 한 칸에 적혀 있다.
      final c = parseChordText(n[4] as String);
      spec = ChordSpec(
        root: spec.root,
        type: c.type.isEmpty ? spec.type : c.type,
        tensions: c.tensions,
        // 슬래시 베이스는 **도수**로 적혀 있다 — 그 조의 그 도수 뿌리음으로 푼다.
        bass: c.bassDegree == null ? null : chords[c.bassDegree!].root,
      );
    }
    specs.add(spec);
    octs.add(n.length > 5 && n[5] is int ? n[5] as int : 0);
  }

  // ── 자리바꿈으로 잇는다 (theory.dart `voiceLead`) ──
  // 클립은 되풀이되므로 **끝 코드 → 첫 코드**도 이어져야 한다. 그래서 두 번 돈다:
  // 첫 바퀴로 마지막 자리를 알아내고, 두 번째 바퀴는 그것을 앞 코드로 삼는다.
  // 난수가 없어 두 바퀴는 항상 같은 답을 낸다.
  List<int>? prev;
  var voiced = <List<int>>[];
  for (var pass = 0; pass < 2; pass++) {
    voiced = <List<int>>[];
    for (var si = 0; si < specs.length; si++) {
      final spec = specs[si];
      // 슬래시 코드는 맨 밑음이 정해져 있다 — 자리를 안 바꾼다.
      final mid = isGuitar ? guitarChordMidi(spec) : chordMidiOf(spec);
      final v = (spec.bass != null || isGuitar)
          ? mid
          : voiceLead(mid, prev, oct: octs[si]);
      voiced.add(v);
      prev = v;
    }
  }

  final out = <ChordHit>[];
  for (var i = 0; i < tiled.length; i++) {
    final n = tiled[i];
    out.add(
      ChordHit(n[1] as int, n[2] as int, n[3] as int, [
        for (final m in voiced[i]) midiFreq(m),
      ]),
    );
  }
  return out;
}

