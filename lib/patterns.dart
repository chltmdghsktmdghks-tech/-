//
// 웹의 곡 데이터(`MIDI_LIB`/`LONG_LIB`/`LONG_LIB2`/`SONG_FORMS`/`GENRE_MIX`, app.html) 중
// 이번엔 **드럼 패턴**만 옮겼다. 베이스/코드/멜로디는 스케일·키·코드 시스템(`SCALE`/`KEY`/
// `CHORDS`/`degRow`)이 함께 필요해서 다음 덩어리로 미뤘다 — 드럼은 그런 의존이 없어서
// (스텝 번호만 있으면 됨) 가장 먼저 떼어낼 수 있는 덩어리였다.
//
// 웹은 세 표를 합쳐 쓴다(`Object.keys(LONG_LIB).forEach(k=>MIDI_LIB[k]=MIDI_LIB[k].concat(...))`,
// app.html:2754,2867). 여기서는 처음부터 하나의 리스트 뒤에 이어 붙이는 것으로 그 결과와
// 같은 순서를 만들었다 — `kDrumPatterns` 안의 주석이 원래 어느 표에서 왔는지 표시한다.
//
// **값은 하나도 손대지 않았다.** 72개 패턴 전부 app.html 을 파이썬 스크립트로 파싱해
// 옮겼다(사람이 손으로 옮기면 64자리 스텝 배열에서 오탈자가 나기 쉽다 — 숫자 하나만 밀려도
// 리듬이 미묘하게 달라지고 귀로는 알아채기 어렵다). 이름이 겹치는 패턴이 있다
// (예: LONG_LIB2 의 'Pop Verse' 는 MIDI_LIB 의 무언가와 겹치지 않지만, 장르별로 비슷한
// 이름 패턴이 여럿이다) — 웹처럼 이름은 유일성이 보장되지 않으므로 `findDrumPattern` 은
// **처음 찾은 것**을 돌려준다(웹 `Array.find` 와 동일한 동작).

/// 마디당 스텝 수 — 웹 `SPB` 기본값(4/4, 16분음표 그리드). 웹은 박자표(3/4·6/8 등)에 따라
/// 바뀌지만(`meterSteps()`) 그 UI가 아직 없어 지금은 4/4 고정값만 쓴다.
const int kStepsPerBar = 16;

/// 웹 `buildDrum()` 이 만드는 lane 이름 — `DrumVoice`(drums.dart)의 악기 키와 그대로 맞는다.
const List<String> kDrumLanes = [
  'kick',
  'snare',
  'hat',
  'tom',
  'crash',
  'rim',
  'clap',
  'shaker',
  'cowbell',
  'ride',
];

/// 웹 패턴 표의 압축 키 → lane 이름. 패턴 데이터 자체는 웹 키(k/s/h/...) 그대로 옮겼으니
/// 해석할 때만 이 표로 풀어준다.
const Map<String, String> kDrumAbbrevToLane = {
  'k': 'kick',
  's': 'snare',
  'h': 'hat',
  't': 'tom',
  'cr': 'crash',
  'rm': 'rim',
  'cp': 'clap',
  'sh': 'shaker',
  'cb': 'cowbell',
  'rd': 'ride',
};

/// 위 표의 반대 방향 — 편집기가 고친 걸 **웹과 같은 형식으로** 되돌려 담을 때 쓴다.
final Map<String, String> kDrumLaneToAbbrev = {
  for (final e in kDrumAbbrevToLane.entries) e.value: e.key,
};

/// 드럼 패턴 하나 — 웹 `MIDI_LIB.drum`/`LONG_LIB.drum`/`LONG_LIB2.drum` 원소 그대로.
/// `hits` 는 웹 키(k/s/h/t/cr/rm/cp/sh/cb/rd) → 스텝 번호 목록.
class DrumPatternDef {
  final String name;
  final int bars; // 최종 길이(마디) — `src` 보다 길면 타일링(반복)한다
  final int src; // 원본 데이터가 담당하는 마디 수
  final Map<String, List<int>> hits;

  /// 타격별 세기(1~3) — `hits[레인]` 과 **자리를 맞춘** 목록이다(같은 순서, 같은 개수).
  /// 없으면(null) 아래 `buildDrumPattern` 의 레인 기본값을 쓴다.
  ///
  /// 라이브러리 72개 패턴은 전부 null 이다 — **웹과 같은 소리를 유지해야 한다.**
  /// 편집기에서 세기를 만진 패턴만 이 칸이 채워진다(5단계 12/N).
  final Map<String, List<int>>? vels;

  /// **이 판의 한 마디가 몇 칸인가** (5단계 47/N · 홀수 박자).
  ///
  /// 여태 마디는 늘 16칸이었다. 3/4 판은 12칸, 7/8 판은 14칸이다.
  /// 판이 제 박자를 **들고 다녀야** 한 앱 안에 4/4 판과 3/4 판이 같이 있어도
  /// 안 어긋난다 — 옛 앱은 격자만 바꾸고 판은 16칸 그대로여서, 3/4 에서 판을
  /// 고르면 12~15칸이 다음 마디로 넘쳤다(그래서 박자를 바꿀 때 곡을 지웠다).
  ///
  /// 기본값이 16이라 **옛 판·옛 파일은 한 톨도 안 달라진다.**
  final int spb;

  const DrumPatternDef(
    this.name,
    this.bars,
    this.src,
    this.hits, [
    this.vels,
    this.spb = kStepsPerBar,
  ]);
}

/// 타격 하나 — 웹 `buildDrum()`/`tileNotes()` 결과 원소(len 은 드럼에선 항상 1이라 뺐다 —
/// `engine.scheduleDrum()` 은 지속시간을 안 받는다, 타격이라 의미가 없다).
class DrumHit {
  final String lane;
  final int step;
  final int vel;
  const DrumHit(this.lane, this.step, this.vel);
}

/// 세기를 따로 정하지 않은 타격의 기본 세기 — 웹 `buildDrum()` 안의 규칙 그대로.
/// 편집기도 이 함수를 쓴다(규칙을 두 군데 적으면 한쪽만 고치는 날이 온다).
int defaultDrumVel(String lane, int step) {
  if (lane == 'hat') return step % 4 == 0 ? 2 : 1; // 웹: vel:s%4===0?2:1
  if (lane == 'shaker' || lane == 'cowbell' || lane == 'ride') return 2;
  return 3;
}

/// 웹 `buildDrum(def)` — 압축 표기를 (lane,step,vel) 목록으로 풀고, `tileNotes()` 로
/// `src` 마디 단위를 `bars` 마디까지 반복한다. 웹 두 함수를 합쳐 옮겼다(로직은 동일).
List<DrumHit> buildDrumPattern(DrumPatternDef def) {
  final one = <DrumHit>[];
  def.hits.forEach((abbrev, steps) {
    final lane = kDrumAbbrevToLane[abbrev];
    if (lane == null) return;
    final mine = def.vels?[abbrev]; // 편집기에서 정한 세기(있으면 이게 이긴다)
    for (var i = 0; i < steps.length; i++) {
      final s = steps[i];
      final vel = (mine != null && i < mine.length)
          ? mine[i].clamp(1, 3)
          : defaultDrumVel(lane, s);
      one.add(DrumHit(lane, s, vel));
    }
  });
  // 웹 tileNotes: reps=max(1, floor(bars/src))
  final reps = def.src > 0 ? (def.bars ~/ def.src).clamp(1, 1 << 20) : 1;
  if (reps <= 1) return one;
  final out = <DrumHit>[];
  for (var r = 0; r < reps; r++) {
    // **이 판의 마디 길이**로 민다 — 곡의 박자가 아니다. 판이 제 박자를 들고 다닌다.
    final off = r * def.src * def.spb;
    for (final h in one) {
      out.add(DrumHit(h.lane, h.step + off, h.vel));
    }
  }
  return out;
}

/// 드럼의 `tileNoteList` 짝 — **압축 형식(약칭 키 · vels 짝) 그대로** 펴서 돌려준다.
///
/// `buildDrumPattern` 은 펼친 결과를 재생용 `DrumHit` 목록으로 바꿔 버려서,
/// 다시 `DrumPatternDef` 에 넣을 수 있는 형태가 필요한 자리(`Project.makeEditable`
/// 이 라이브러리 패턴을 사용자 패턴으로 복사할 때)에는 못 쓴다. 그래서 따로 있다.
///
/// [vels] 는 `hits[약칭]` 과 **자리를 맞춘** 목록이라는 계약을 그대로 지킨다 —
/// 라이브러리 패턴은 전부 null 이라 실전에서는 세기 쪽 되풀이는 안 타지만,
/// 혹시 있을 경우까지 안전하게 짝을 맞춘다(모자란 자리는 `defaultDrumVel` 로 채운다).
(Map<String, List<int>>, Map<String, List<int>>?) tileDrumHits(
  Map<String, List<int>> hits,
  Map<String, List<int>>? vels,
  int src,
  int bars, {
  int spb = kStepsPerBar,
}) {
  final reps = src > 0 ? (bars ~/ src).clamp(1, 1 << 20) : 1;
  final outHits = <String, List<int>>{};
  final outVels = vels == null ? null : <String, List<int>>{};
  hits.forEach((ab, steps) {
    final vs = vels?[ab];
    final lane = kDrumAbbrevToLane[ab] ?? ab;
    final newSteps = <int>[];
    final newVels = vs == null ? null : <int>[];
    for (var r = 0; r < reps; r++) {
      final off = r * src * spb;
      for (var i = 0; i < steps.length; i++) {
        newSteps.add(steps[i] + off);
        if (vs != null) {
          newVels!.add(i < vs.length ? vs[i] : defaultDrumVel(lane, steps[i]));
        }
      }
    }
    outHits[ab] = newSteps;
    if (outVels != null) outVels[ab] = newVels!;
  });
  return (outHits, outVels);
}

/// 이름으로 찾는다 — 웹 `MIDI_LIB[type].find(d=>d.name===name)` 대응.
/// 이름이 유일하지 않을 수 있어(웹도 마찬가지) 처음 찾은 것을 돌려준다.
DrumPatternDef? findDrumPattern(String name) {
  for (final d in kDrumPatterns) {
    if (d.name == name) return d;
  }
  return null;
}

